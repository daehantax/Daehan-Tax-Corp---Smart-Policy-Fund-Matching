const TAGS = new Set(SECTORS.map((s) => s.tag));
/** 꼬리표 이름으로 설명을 찾는다 (화면에 「부동산 임대업」처럼 보여 주려고) */
export const sectorLabel = (tag) => SECTORS.find((s) => s.tag === tag)?.label ?? tag;
export const isSectorTag = (tag) => TAGS.has(tag);

/**
 * 업종 **이름** 하나를 꼬리표로 바꾼다. 맞는 것이 없으면 빈 배열.
 *
 * 띄어쓰기를 지우고 본다 — 조견표는 「일반 유흥 주점업」, 공고는 「일반유흥주점업」이라
 * 그대로 비교하면 하나도 안 맞는다.
 */
export function sectorsOfName(name) {
  const s = String(name ?? '');
  if (!s.trim()) return [];
  const flat = s.replace(/\s+/g, '');
  return SECTORS.filter((x) => x.name.test(s) || x.name.test(flat)).map((x) => x.tag);
}

/** KSIC 5자리 코드 하나를 꼬리표로 바꾼다. 공고가 코드까지 적어 줬을 때만 쓴다 */
export function sectorsOfKsic(code) {
  const c = String(code ?? '').trim();
  if (!/^\d{5}$/.test(c)) return [];
  return SECTORS.filter((x) => x.ksic.includes(c)).map((x) => x.tag);
}

/**
 * 국세청 조견표 한 줄을 꼬리표로 바꾼다 — **우리 거래처 쪽**이다.
 *
 * 세세분류(종목)가 가장 구체적이라 먼저 본다. 셋 다 봐야 하는 이유:
 * 「701101 주거용 건물 임대업」은 세세분류에 '임대'가 있지만,
 * 「부동산 임대 및 공급업」처럼 세분류에만 있는 줄도 있다.
 */
export function sectorsOfIndustryRow(row) {
  const out = new Set();
  for (const field of [row?.detail_category, row?.sub_category, row?.mid_category]) {
    for (const t of sectorsOfName(field)) out.add(t);
  }
  return [...out];
}
